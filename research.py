"""Robustness checks on the breakout backtest: is the result real, or luck?

1. Equity curves and drawdowns (results/*.png)
2. Stability (crypto year split in two halves) and true out-of-sample (trades after the rule was written down)
3. Bootstrap: 95 % confidence interval of the mean R per trade
4. Macro releases: breakouts triggered around US data releases vs the rest of the day

    python research.py   # writes results/report.md and the charts
"""
from datetime import date, time
from pathlib import Path

import matplotlib
import numpy as np
import pandas as pd

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

from backtest import ASSETS, MODES, summary, trades  # noqa: E402

RESULTS = Path(__file__).parent / "results"
FX = ["EUR/USD", "GBP/USD", "USD/JPY", "AUD/USD", "USD/CAD", "USD/CHF"]
CRYPTO = ["Bitcoin", "Ethereum"]
# FOMC decision days in the sample (federalreserve.gov), statement at 2pm New York time
FOMC = {date(2025, 10, 29), date(2025, 12, 10), date(2026, 1, 28), date(2026, 3, 18),
        date(2026, 4, 29), date(2026, 6, 17), date(2026, 7, 29), date(2026, 9, 16)}
RULE_FIXED = date(2026, 10, 1)  # strategy written down on 30 Sep 2026; trades from the next day on
RED, GREY, INK = "#7b1730", "#9a9a9a", "#1c1c1c"
rng = np.random.default_rng(42)


def bootstrap(r, n=10_000):
    """95 % interval of the mean R, and share of resamples with a positive mean."""
    if len(r) < 2:
        return float("nan"), float("nan"), float("nan")
    means = rng.choice(r.to_numpy(), (n, len(r))).mean(axis=1)
    return np.percentile(means, 2.5), np.percentile(means, 97.5), (means > 0).mean()


def in_release_window(t):
    """US data come out at 8:30am New York time (NFP, CPI, PCE, GDP, jobless claims...),
    FOMC statements at 2pm. Window = 15 min before to 15 min after."""
    ny = t.tz_convert("America/New_York")
    if ny.weekday() >= 5:
        return False
    if time(8, 15) <= ny.time() <= time(8, 45):
        return True
    return ny.date() in FOMC and time(13, 45) <= ny.time() <= time(14, 15)


def row(label, r):
    lo, hi, p = bootstrap(r)
    s = summary(r)
    return (f"| {label} | {s['trades']} | {s['win rate']:.0%} | {s['mean R']:+.2f} | [{lo:+.2f} ; {hi:+.2f}] "
            f"| {p:.0%} |")


HEADER = ("| | Trades | Win rate | Mean R | 95 % interval | Resamples > 0 |\n"
          "|---|---|---|---|---|---|")


def chart_equity(results):
    fig, axes = plt.subplots(1, 2, figsize=(11, 3.8), sharey=False)
    for ax, mode in zip(axes, MODES):
        for name, color in (("Bitcoin", RED), ("Ethereum", INK)):
            r = results[(name, mode)]
            ax.plot(r.index, r.cumsum(), color=color, lw=1.6, label=name)
        fx = pd.concat([results[(n, mode)] for n in FX]).sort_index()
        ax.plot(fx.index, fx.cumsum(), color=GREY, lw=1.6, label="6 FX majors (pooled)")
        ax.axhline(0, color="#cccccc", lw=0.8)
        ax.set_title(MODES[mode], fontsize=10, color=INK)
        ax.set_ylabel("Cumulative R")
        ax.spines[["top", "right"]].set_visible(False)
        ax.tick_params(labelsize=8)
    axes[0].legend(frameon=False, fontsize=8)
    fig.suptitle("Same entries, different stop: my original 15-pip stop is noise on crypto", fontsize=11, color=RED)
    fig.tight_layout()
    fig.savefig(RESULTS / "equity_curves.png", dpi=160)
    plt.close(fig)


def chart_scaled_crypto(results):
    fig, ax = plt.subplots(figsize=(8, 3.4))
    for name, color in (("Bitcoin", RED), ("Ethereum", INK)):
        r = results[(name, "scaled")]
        ax.plot(r.index, r.cumsum(), color=color, lw=1.6, label=name)
        half = r.index[len(r) // 2]
    ax.axvline(half, color=GREY, ls="--", lw=1)
    ax.text(half, ax.get_ylim()[1], "  second half →", va="top", fontsize=8, color=GREY)
    ax.axhline(0, color="#cccccc", lw=0.8)
    ax.set_ylabel("Cumulative R")
    ax.set_title("Volatility-scaled stop on BTC/ETH, one year, spread included", fontsize=10, color=INK)
    ax.spines[["top", "right"]].set_visible(False)
    ax.tick_params(labelsize=8)
    ax.legend(frameon=False, fontsize=8)
    fig.tight_layout()
    fig.savefig(RESULTS / "crypto_scaled.png", dpi=160)
    plt.close(fig)


def main():
    RESULTS.mkdir(exist_ok=True)
    results = {(n, m): trades(n, m)[0] for n in ASSETS for m in MODES}
    chart_equity(results)
    chart_scaled_crypto(results)
    out = ["# Robustness report", "",
           f"Generated by `research.py` from the data snapshot in `data/`. Spread included, 10,000 bootstrap resamples.",
           "", "## 1. Full sample, by asset", ""]
    for mode, title in MODES.items():
        out += [f"**{title}**", "", HEADER]
        out += [row(n, results[(n, mode)]) for n in ASSETS]
        out += [row("FX majors pooled", pd.concat([results[(n, mode)] for n in FX])),
                row("BTC + ETH pooled", pd.concat([results[(n, mode)] for n in CRYPTO])), ""]

    out += ["## 2. Stability and out-of-sample (crypto, volatility-scaled stop)", "",
            "Stability: the same rule on each half of the year. Both halves were visible when the rule was chosen, "
            "so this is a stability check, not a true out-of-sample test.", "",
            f"Out-of-sample: trades after {RULE_FIXED:%d %b %Y}, the day the rule was written down "
            "(small sample, updated as data comes in).", "", HEADER]
    for name in CRYPTO + ["BTC + ETH"]:
        r = (pd.concat([results[(n, "scaled")] for n in CRYPTO]).sort_index() if name == "BTC + ETH"
             else results[(name, "scaled")])
        cut = r.index[len(r) // 2]
        out += [row(f"{name}, {r.index[0]:%b %Y}–{cut:%b %Y}", r[r.index < cut]),
                row(f"{name}, {cut:%b %Y}–{r.index[-1]:%b %Y}", r[r.index >= cut])]
    oos = pd.concat([results[(n, "scaled")] for n in CRYPTO])
    out += [row(f"BTC + ETH, out-of-sample since {RULE_FIXED:%d %b %Y}",
                oos[oos.index >= pd.Timestamp(RULE_FIXED, tz="UTC")]), ""]

    out += ["## 3. Breakouts around US macro releases", "",
            "Release window: 8:15–8:45am New York time on weekdays (8:30 data: NFP, CPI, PCE, GDP, jobless claims…) "
            "and 1:45–2:15pm on FOMC days.", ""]
    for mode, title in MODES.items():
        out += [f"**{title}**", "", HEADER]
        for group, names in (("FX majors + gold", FX + ["Gold"]), ("BTC + ETH", CRYPTO)):
            r = pd.concat([results[(n, mode)] for n in names])
            inside = r.index.map(in_release_window).to_numpy(bool)
            out += [row(f"{group}, inside window", r[inside]), row(f"{group}, outside window", r[~inside])]
        out += [""]
    (RESULTS / "report.md").write_text("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
